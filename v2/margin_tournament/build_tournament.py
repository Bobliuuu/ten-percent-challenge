"""MARGIN TOURNAMENT dev-set builder. Public data only; NO locked exam file is read.
Hash-lock recipe: h = sha256(f"{task}|{src}|{rid}"); bucket = int(h[:8],16) % 10.
bucket 0,1 = EXAM-CANDIDATE bucket (ids hashed + counted in manifest, text never written, never scored).
bucket >=2 = DEV pool; per (source,label) cell the lowest-hash rows are taken up to a cap.
Tasks reused from earlier lanes (TOX, TOOLSEL, LANGID, NEWS, INJR) keep their existing dev rows.
Output (not committed: raw dataset text): items_tour.jsonl ; committed: manifest.json.
Usage: python3 build_tournament.py <out_dir>"""
import json, hashlib, collections, sys, os, re, random
from datasets import load_dataset
OUT = sys.argv[1]; os.makedirs(OUT, exist_ok=True)
HERE = os.path.dirname(os.path.abspath(__file__)); TS = HERE + "/../task_search/"
H = lambda s: hashlib.sha256(s.encode()).hexdigest()
def stream(a, c, s, n, flt=None):
    d = load_dataset(a, c, split=s, streaming=True); k = 0
    for r in d:
        if flt and not flt(r): continue
        yield r; k += 1
        if k >= n: break
def trunc(t, n=700): t = " ".join(str(t).split()); return t if len(t) <= n else t[:n] + " ..."
items = []; MAN = {}
def add(task, role, src, rows, instr, labels, target=1600, nsrc=2):
    """rows: (rid, label, payload). payload substituted into instr {X}."""
    cap = int(max(20, target // (nsrc * len(labels)))); by = collections.defaultdict(list); exam = collections.Counter()
    for rid, lab, pl in rows:
        h = H(f"{task}|{src}|{rid}")
        if int(h[:8], 16) % 10 < 2: exam[lab] += 1; continue
        by[lab].append((h, rid, lab, pl))
    n = collections.Counter()
    for lab, v in by.items():
        v.sort()
        for h, rid, l, pl in v[:cap]:
            items.append(dict(id=f"{task}|{src}|{rid}", task=task, role=role, src=src, kind=l, user=instr.replace("{X}", pl).replace("{M}", ", ".join(labels)), answer=l)); n[l] += 1
    MAN.setdefault(task, {})[src] = dict(dev=dict(n), exam_bucket_count=dict(exam), cap_per_cell=cap)
    print(task, src, sum(n.values()), dict(n), flush=True)
def tryb(f):
    try: f()
    except Exception as e: print("BUILD FAIL", f.__name__, repr(e)[:200], flush=True)

# ---- PIITYPE (ai4privacy + gretel finance): name the type of a highlighted PII span
PL = ["NAME", "EMAIL", "PHONE", "ADDRESS", "DATE", "SSN", "PASSPORT", "DRIVERLICENSE", "IP", "USERNAME", "PASSWORD"]
PI = "A document contains the highlighted span <<...>>. Which type of personal data is the span?\nAnswer with exactly one word from: {M}.\n\nText: {X}"
M1 = dict(GIVENNAME1="NAME", GIVENNAME2="NAME", LASTNAME1="NAME", LASTNAME2="NAME", LASTNAME3="NAME", EMAIL="EMAIL", TEL="PHONE", STREET="ADDRESS", DATE="DATE", SOCIALNUMBER="SSN", PASSPORT="PASSPORT", DRIVERLICENSE="DRIVERLICENSE", IP="IP", USERNAME="USERNAME", PASS="PASSWORD")
M2 = dict(name="NAME", first_name="NAME", last_name="NAME", email="EMAIL", phone_number="PHONE", street_address="ADDRESS", date="DATE", ssn="SSN", passport_number="PASSPORT", driver_license_number="DRIVERLICENSE", ipv4="IP", ipv6="IP", user_name="USERNAME", password="PASSWORD")
def ctx(t, s, e, v):
    a = max(0, s - 280); b = min(len(t), e + 280)
    return trunc(t[a:s] + "<<" + t[s:e] + ">>" + t[e:b], 900)
def piitype():
    rows = []
    for i, r in enumerate(stream("ai4privacy/pii-masking-300k", None, "train", 30000, lambda r: r["language"] == "English")):
        t = r["source_text"]; pm = r["privacy_mask"]; pm = json.loads(pm) if isinstance(pm, str) else pm
        for j, m in enumerate(pm):
            if m["label"] in M1: rows.append((f"{r['id']}_{j}", M1[m["label"]], ctx(t, m["start"], m["end"], m["value"])))
    add("PIITYPE", "S1", "ai4privacy", rows, PI, PL)
    rows = []
    for i, r in enumerate(stream("gretelai/synthetic_pii_finance_multilingual", None, "train", 4000, lambda r: r["language"] == "English")):
        t = r["generated_text"]
        for j, m in enumerate(json.loads(r["pii_spans"])):
            if m["label"] in M2: rows.append((f"{r['index']}_{j}", M2[m["label"]], ctx(t, m["start"], m["end"], "")))
    add("PIITYPE", "S3", "gretel_fin", rows, PI, PL)
tryb(piitype)

# ---- AIHUM: AI vs human text
AI = "Decide whether the following text was written by a human or generated by an AI language model.\nAnswer with exactly one word: Human or AI.\n\nText: {X}"
def aihum():
    rows = [(i, "Human" if "human" in r["src"] else "AI", trunc(r["text"])) for i, r in enumerate(stream("yaful/MAGE", None, "train", 40000)) if len(r["text"]) > 200]
    add("AIHUM", "S1", "mage", rows, AI, ["Human", "AI"])
    rows = [(r["id"], "Human" if r["model"] == "human" else "AI", trunc(r["generation"])) for r in stream("liamdugan/raid", None, "train", 20000) if r["attack"] == "none" and r["decoding"] in ("None", "greedy") or (r["model"] == "human")]
    add("AIHUM", "S3", "raid_abstracts", rows, AI, ["Human", "AI"])
tryb(aihum)

# ---- VOICE7: voice-assistant skill router (MASSIVE + CLINC150, 7 skills)
VK = {"weather": "weather conditions and forecasts", "email": "reading, writing, sending or managing email", "transport": "taxis, trains, flights, traffic and directions", "lists": "shopping lists and to-do lists", "calendar": "calendar events, meetings and reminders", "home": "smart-home device control", "news": "news headlines and updates"}
VI = "You route requests for a voice assistant to the skill that should handle them.\nSkills:\n" + "\n".join(f"- {k}: {v}" for k, v in VK.items()) + "\nAnswer with exactly one word from: {M}.\n\nRequest: {X}"
MB = dict(weather="weather", email="email", transport="transport", lists="lists", calendar="calendar", iot="home", news="news")
CL = {"weather": ["weather"], "transport": ["uber", "traffic", "directions", "distance", "book_flight", "flight_status", "car_rental"], "lists": ["shopping_list", "shopping_list_update", "todo_list", "todo_list_update"], "calendar": ["calendar", "calendar_update", "meeting_schedule", "schedule_meeting", "reminder", "reminder_update"], "home": ["smart_home"]}
def voice7():
    rows = [(f"m{i}", MB[r["label_text"]], r["text"]) for i, r in enumerate(stream("mteb/amazon_massive_scenario", "en", "train", 20000)) if r["label_text"] in MB]
    add("VOICE7", "S1", "massive_en", rows, VI, list(VK))
    d = load_dataset("clinc/clinc_oos", "plus", split="train", streaming=True); names = d.features["intent"].names
    inv = {v: k for k, vs in CL.items() for v in vs}; rows = []
    for sp in ("train", "validation", "test"):
        for i, r in enumerate(load_dataset("clinc/clinc_oos", "plus", split=sp, streaming=True)):
            n = names[r["intent"]]
            if n in inv: rows.append((f"c{sp}{i}", inv[n], r["text"]))
    add("VOICE7", "S3", "clinc150", rows, VI, list(VK))
tryb(voice7)

