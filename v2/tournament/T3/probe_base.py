"""T3 base probe (Modal, vLLM, greedy, same prompts / chat template for every model). Reads ONLY dev_S1 / dev_S3 from volume tenpct-t3-exam
(never locked_*). 150 human + 150 ai from each of S1-dev and S3-dev. Two FIXED zero-shot prompts (no examples, no retrieval, no fitted parts):
 P0 plain question, P1 same + fixed task instruction listing generic AI-vs-human cues. Output = the model's generated verdict ('human'/'ai').
Run: modal run --detach probe_base.py [--models a,b]    Results: volume /d/results/<model>.json  -> modal volume get tenpct-t3-exam results ."""
import modal, json, os, hashlib
app = modal.App("tenpct-t3-probe")
img = (modal.Image.debian_slim(python_version="3.12").pip_install("vllm==0.10.2", "transformers==4.56.2", "huggingface_hub<1.0", "hf_transfer")
       .env({"HF_HUB_ENABLE_HF_TRANSFER": "1"}).add_local_file(os.path.join(os.path.dirname(os.path.abspath(__file__)), "scorer.py"), "/root/scorer.py"))
vol = modal.Volume.from_name("tenpct-t3-exam"); hfv = modal.Volume.from_name("tenpct-v2-hf")
MODELS = {  # name -> (gpu, fp16-equivalent params, extra chat kwargs)
    "Qwen/Qwen3-30B-A3B-Instruct-2507": ("A100-80GB", 30.53e9, {}),
    "Qwen/Qwen2.5-32B-Instruct": ("A100-80GB", 32.76e9, {}),
    "Qwen/Qwen3-14B": ("A100-80GB", 14.77e9, {"enable_thinking": False}),
    "Qwen/Qwen3-8B": ("A100-80GB", 8.19e9, {"enable_thinking": False}),
    "openai/gpt-oss-20b": ("H100", 20.91e9, {"reasoning_effort": "low"}),
}
P0 = 'Was the following text written by a human or generated by an AI language model? Answer with exactly one word: "human" or "ai".\n\nText:\n"""\n{t}\n"""'
P1 = ('Task: AI-generated text detection. Decide whether the text below was written by a human or generated by an AI language model (a chatbot / LLM).\n'
      'Cues: AI text tends to be fluent, polite, neutral and generic, with balanced hedged statements, tidy structure, formulaic transitions and summaries, '
      'and few typos or slang. Human text more often has a personal voice, informal or inconsistent register, typos, abrupt or uneven structure, '
      'concrete idiosyncratic details, opinions, and noise (quotes, links, odd formatting).\n'
      'Weigh the cues and commit to the more likely source. Do not explain. Reply with exactly one word: "human" or "ai".\n\nText:\n"""\n{t}\n"""')
PROMPTS = {"P0": P0, "P1": P1}

def _run(model):
    import sys
    sys.path.insert(0, "/root")
    os.environ["HF_HOME"] = "/hf"
    import scorer, numpy as np
    from vllm import LLM, SamplingParams
    _, nparams, kw = MODELS[model]
    def load(f):
        rows = [json.loads(l) for l in open(f"/d/data/{f}")]; out = []
        for gold in ("human", "ai"):
            rr = sorted([r for r in rows if r["gold"] == gold], key=lambda r: hashlib.sha256(("probe" + r["id"]).encode()).hexdigest())
            out += rr[:150]
        return out
    items = load("dev_S1.jsonl") + load("dev_S3.jsonl")
    llm = LLM(model, dtype="bfloat16", max_model_len=4096, gpu_memory_utilization=0.92, enable_prefix_caching=False, seed=0)
    gptoss = "gpt-oss" in model
    sp = SamplingParams(temperature=0, max_tokens=1024 if gptoss else 12, logprobs=None if gptoss else 20, skip_special_tokens=not gptoss)
    res = {"model": model, "n": len(items), "nparams": nparams, "prompts": {}}
    for pn, pt in PROMPTS.items():
        msgs = [[{"role": "user", "content": pt.format(t=r["text"])}] for r in items]
        outs = llm.chat(msgs, sp, chat_template_kwargs=kw or None, use_tqdm=False)
        rows = []
        for r, o in zip(items, outs):
            c = o.outputs[0]; sc = None
            if c.logprobs:
                lp = c.logprobs[0]; a = [v.logprob for v in lp.values() if (v.decoded_token or "").strip().lower().startswith("ai")]
                h = [v.logprob for v in lp.values() if (v.decoded_token or "").strip().lower().startswith("human")]
                if a or h: sc = float(np.logaddexp.reduce(a) if a else -30) - float(np.logaddexp.reduce(h) if h else -30)
            v = scorer.parse_verdict(c.text)
            rows.append(dict(id=r["id"], source=r["source"], kind=r["kind"], domain=r["domain"], generator=r["generator"], gold=r["gold"], out=c.text, pred=v, correct=v == r["gold"], ai_minus_human_logit=sc, out_tokens=len(c.token_ids)))
        res["prompts"][pn] = dict(items=rows, summary=scorer.summarize(rows))
        print(model, pn, json.dumps(res["prompts"][pn]["summary"]), flush=True)
    os.makedirs("/d/results", exist_ok=True)
    json.dump(res, open("/d/results/" + model.replace("/", "__") + ".json", "w"))
    vol.commit()
    return {pn: v["summary"] for pn, v in res["prompts"].items()}

GPUS = {"big": ["A100-80GB", "H100", "H200"], "small": ["A100-40GB", "L40S", "A100-80GB", "H100"], "oss": ["H100", "H200", "A100-80GB"]}
_kw = dict(image=img, volumes={"/d": vol, "/hf": hfv}, timeout=3 * 3600)
@app.function(gpu=GPUS["big"], **_kw)
def run_big(model): return _run(model)
@app.function(gpu=GPUS["small"], **_kw)
def run_small(model): return _run(model)
@app.function(gpu=GPUS["oss"], **_kw)
def run_oss(model): return _run(model)
FN = {"big": run_big, "small": run_small, "oss": run_oss}
def kind(m): return "oss" if "gpt-oss" in m else ("small" if m.endswith(("14B", "8B")) else "big")

@app.local_entrypoint()
def main(models: str):
    # client must stay alive (run under nohup/setsid); also --detach so the app survives if it dies. Results -> volume + local results/
    m = models
    c = FN[kind(m)].spawn(m); print("SPAWNED", m, c.object_id, flush=True)
    r = c.get(); print("DONE", m, json.dumps(r), flush=True)
