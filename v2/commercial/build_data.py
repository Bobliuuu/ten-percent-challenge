def build_B():
    import csv, random
    from huggingface_hub import hf_hub_download
    csv.field_size_limit(10**9)
    def load(fn):
        out=[]
        for r in csv.DictReader(open(hf_hub_download("yaful/MAGE",fn,repo_type="dataset"),encoding="utf-8-sig")):
            tx=" ".join(r["text"].split())
            if len(tx)<200: continue
            out.append(dict(text=tx[:1500],answer=0 if r["label"]=="1" else 1,src=r["src"]))
        return out
    te=load("test.csv"); ca=load("train.csv")
    b=assign(te,"B",lambda r:r["text"],CAP)
    random.Random(2).shuffle(ca); b["calib"]=ca[:CAP["calib"]]
    return {k:[dict(task="B",text=r["text"],answer=r["answer"],names=B_NAMES,inst=B_INST,src=r["src"]) for r in v] for k,v in b.items()}

def build_C():
    import random, pyarrow.parquet as pq, json as J
    from huggingface_hub import hf_hub_download
    t=pq.read_table(hf_hub_download("argilla/apigen-function-calling","data/train-00000-of-00001.parquet",repo_type="dataset")).to_pylist()
    seen=set(); rows=[]
    for r in t:
        if r["query"] in seen: continue
        seen.add(r["query"])
        try: tools=J.loads(r["tools"]); ans=J.loads(r["answers"])
        except Exception: continue
        names={a["name"] for a in ans}
        if len(names)!=1 or not tools: continue
        g=list(names)[0]; tl={x["name"]:x for x in tools if isinstance(x,dict) and "name" in x}
        if g not in tl: continue
        rows.append(dict(query=r["query"],tools=tools,answers=ans,gold=g,origin=r["origin"]))
    for r in rows: r["h"]=hsel("C",r["query"])
    rows.sort(key=lambda r:r["h"])
    # 4 splits by hash: locked %7==0, dev ==1, calib ==2 (kept apart from pool), pool rest
    sp={"locked":[r for r in rows if r["h"]%7==0],"dev":[r for r in rows if r["h"]%7==1],"calib":[r for r in rows if r["h"]%7==2],"pool":[r for r in rows if r["h"]%7>2]}
    def desc(x):
        ps=list((x.get("parameters") or {}).keys()) if isinstance(x.get("parameters"),dict) else []
        return f"{x['name']}: {x.get('description','')}"[:220]+(f" (params: {', '.join(ps[:6])})" if ps else "")
    out={}
    for k,v in sp.items():
        v=v[:CAP[k]]; pool=[x for r in sp[k] for x in r["tools"] if isinstance(x,dict) and "name" in x]
        res=[]
        for r in v:
            rng=random.Random(hsel("Copt",r["query"])); gold={x["name"]:x for x in r["tools"] if isinstance(x,dict) and "name" in x}
            irrelevant=rng.random()<0.2
            opts=[] if irrelevant else [gold[r["gold"]]]
            used={r["gold"]}
            others=[x for n,x in gold.items() if n!=r["gold"]]; rng.shuffle(others)
            for x in others:
                if len(opts)>=4: break
                opts.append(x); 
            tries=0
            while len(opts)<4 and tries<200:
                x=rng.choice(pool); tries+=1
                if x["name"] in used or any(o["name"]==x["name"] for o in opts): continue
                opts.append(x)
            if len(opts)<4: continue
            rng.shuffle(opts)
            names=[desc(x) for x in opts]+["None of these tools can do this"]
            ans=4 if irrelevant else [o["name"] for o in opts].index(r["gold"])
            res.append(dict(task="C",text=r["query"],answer=ans,names=names,inst="You are an assistant with access to tools. Pick the tool that should be called to satisfy the user request, or say none fits.",
                 tools=json.dumps(r["tools"]),gold_calls=json.dumps(r["answers"]),irrelevant=irrelevant,origin=r["origin"]))
        out[k]=res
    return out

@app.function(image=img, timeout=3600, volumes={"/d":vol})
def build():
    import hashlib, os
    res={"sha":{},"n":{},"dist":{}}
    for T,fn in [("A",lambda:build_A(None)),("B",build_B),("C",build_C)]:
        try: out=fn()
        except Exception as e:
            import traceback; traceback.print_exc(); res["sha"][T]="FAIL "+repr(e); continue
        os.makedirs(f"/d/{T}",exist_ok=True); res["sha"][T]={}; res["n"][T]={}
        import collections
        for k,v in out.items():
            for i,r in enumerate(v): r["id"]=f"{T}-{k}-{i}"
            p=f"/d/{T}/{k}.jsonl"
            with open(p,"w") as f:
                for r in v: f.write(json.dumps(r,ensure_ascii=False)+"\n")
            res["sha"][T][k]=hashlib.sha256(open(p,"rb").read()).hexdigest(); res["n"][T][k]=len(v)
            res["dist"][f"{T}-{k}"]=dict(collections.Counter(r["answer"] for r in v))
        if T=="A": res["dist"]["A-lang-dev"]=dict(collections.Counter(r["lang"] for r in out["dev"]))
        if T=="B": res["dist"]["B-src-dev"]=dict(collections.Counter(r["src"].split("_")[0] for r in out["dev"]))
    vol.commit(); print("RESULT_JSON "+json.dumps(res)); return res
@app.local_entrypoint()
def main(): build.remote()
