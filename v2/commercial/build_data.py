    val=[f for f in files if "/validation/" in f]; tr=[f for f in files if "/train/" in f]
    te=[]
    for f in val: te+=items(hf_hub_download("ai4privacy/pii-masking-300k",f,repo_type="dataset"),10**9)
    ca=[]
