"""v2/commercial: build frozen task suites for the maintainer's three example classes.
Run: modal run --detach build_data.py  (Volume commercial-data:/{A,B,C}/{locked,dev,pool,calib}.jsonl + RESULT_JSON)
Row schema (all tasks): {id, task, text, answer(int), names[list of option strings], inst, ...}
 A  PII span classification (ai4privacy/pii-masking-300k, 6 languages): is the <<marked span>> PII, and which category (8 options incl NOT_PII)
 B  AI-vs-human text detection (yaful/MAGE, 10 domains x ~27 generators): A=Human, B=AI
 C  Tool selection / irrelevance (argilla/apigen-function-calling = xLAM+ToolACE-style): pick the right tool of 4 or 'none fits'
Split rule: h=int(sha256(task|key)[:8],16); h%7==0 LOCKED, ==1 DEV, else POOL (ascending-h, capped). key = source_text (A), text (B), query (C).
CALIB: from disjoint TRAIN-side data (A: ai4privacy train; B: MAGE train.csv; C: none disjoint -> C calib = pool-hash h%7==2 slice kept apart, see code).
"""
