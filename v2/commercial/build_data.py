CAP = dict(locked=2000, dev=2000, pool=4000, calib=2000)
A_NAMES = ["Person name (given name, surname, title)","Address or location (street, building, city, state, postcode, country, coordinates)",
 "Contact detail (email address, phone number)","Government or document ID (ID card, social security number, passport, driver license)",
 "Date or time (birth date, date, time)","Online identifier or credential (username, password, IP address)",
 "Gender or sex","Not personal data"]
A_MAP = {"GIVENNAME1":0,"GIVENNAME2":0,"LASTNAME1":0,"LASTNAME2":0,"LASTNAME3":0,"TITLE":0,
 "STREET":1,"BUILDING":1,"CITY":1,"STATE":1,"POSTCODE":1,"COUNTRY":1,"SECADDRESS":1,"GEOCOORD":1,
 "EMAIL":2,"TEL":2,"IDCARD":3,"SOCIALNUMBER":3,"PASSPORT":3,"DRIVERLICENSE":3,"BOD":4,"DATE":4,"TIME":4,
 "USERNAME":5,"PASS":5,"IP":5,"SEX":6}
A_INST = "PII detection for redaction: the span between << and >> in the text may be personal data. Classify the span into one category, or say it is not personal data."
B_NAMES = ["Human-written","AI-generated (written by a language model)"]
B_INST = "Decide whether the following text was written by a human or generated by an AI language model."

def hsel(task, key):
    import hashlib
    return int(hashlib.sha256(f"{task}|{key}".encode()).hexdigest()[:8],16)

def assign(rows, task, keyf, caps):
    for r in rows: r["h"]=hsel(task,keyf(r))
    rows.sort(key=lambda r:r["h"])
    return {"locked":[r for r in rows if r["h"]%7==0][:caps["locked"]],"dev":[r for r in rows if r["h"]%7==1][:caps["dev"]],
            "pool":[r for r in rows if r["h"]%7>1][:caps["pool"]]}

