                if len(toks)<3: break
                i0=rng.randrange(len(toks)); n=rng.choice([1,1,2,3]); j=min(i0+n,len(toks))
                s,e=toks[i0][0],toks[j-1][1]; sp=st[s:e].strip(".,;:!?()\"'")
                if not sp: continue
